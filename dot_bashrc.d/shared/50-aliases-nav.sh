#!/usr/bin/env bash
# Navigation shortcuts — cd helpers.

# Easier navigation: .., ..., ...., .....
alias ..='cd ..'
alias ...='cd ../..'
alias ....='cd ../../..'
alias .....='cd ../../../..'

# Change CWD to home folder
alias hh='cd ~'

# CD to /etc
alias ee='cd /etc'

# Move to previous directory
alias -- -='cd -'
